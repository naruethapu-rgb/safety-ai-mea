def create_pdf(filepath: Path, pages: list[str]):
    filepath.parent.mkdir(parents=True, exist_ok=True)
    doc = pymupdf.open()
    for text in pages:
        page = doc.new_page(width=595, height=842)
        if Path(FONT_PATH).exists():
            page.insert_font(fontname="thai", fontfile=FONT_PATH)
            fname = "thai"
        else:
            fname = "helv"
        rect = pymupdf.Rect(50, 50, 545, 792)
        page.insert_textbox(rect, text, fontname=fname, fontsize=11, lineheight=1.35)
    doc.save(str(filepath))
    doc.close()


def generate_all():
    base_docs = Path("C:/SafetyAI/documents")
    count = 0
    for t in TEMPLATES:
        dest = base_docs / t["category"] / t["filename"]
        create_pdf(dest, t["pages"])
        count += 1
    print(f"Generated {count} mock template PDFs in {base_docs}")


if __name__ == "__main__":
    generate_all()
